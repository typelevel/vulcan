package vulcan

import org.scalacheck.Gen
import vulcan.NumberFormatSpec.*
import vulcan.internal.NumberFormat

final class NumberFormatSpec extends BaseSpec {
  describe("NumberFormat") {
    describe("double") {
      it("should format the same as toString on the JVM") {
        doubles.foreach { case (bits, expected) =>
          assert(NumberFormat.double(java.lang.Double.longBitsToDouble(bits)) == expected)
        }
      }

      it("should format zeros") {
        assert(NumberFormat.double(0d) == "0.0")
        assert(NumberFormat.double(-0d) == "-0.0")
      }

      it("should format decimals which parse to the same double") {
        forAll(
          Gen
            .choose(Long.MinValue, Long.MaxValue)
            .map(java.lang.Double.longBitsToDouble)
            .filter(java.lang.Double.isFinite)
        ) { (double: Double) =>
          assert(java.lang.Double.parseDouble(NumberFormat.double(double)) == double)
        }
      }
    }

    describe("float") {
      it("should format the same as toString on the JVM") {
        floats.foreach { case (bits, expected) =>
          assert(NumberFormat.float(java.lang.Float.intBitsToFloat(bits)) == expected)
        }
      }

      it("should format zeros") {
        assert(NumberFormat.float(0f) == "0.0")
        assert(NumberFormat.float(-0f) == "-0.0")
      }

      it("should format decimals which parse to the same float") {
        forAll(
          Gen
            .choose(Int.MinValue, Int.MaxValue)
            .map(java.lang.Float.intBitsToFloat)
            .filter(java.lang.Float.isFinite)
        ) { (float: Float) =>
          assert(java.lang.Float.parseFloat(NumberFormat.float(float)) == float)
        }
      }
    }
  }
}

